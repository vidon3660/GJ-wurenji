import { randomBytes } from "node:crypto"
import { readFile, stat, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const repositoryDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..")

export function createLocalEnvironment(template) {
  const postgresPassword = randomBytes(24).toString("hex")
  const values = {
    POSTGRES_PASSWORD: postgresPassword,
    DATABASE_URL: `postgresql://wurenji:${postgresPassword}@localhost:55432/wurenji`,
    JWT_SECRET: randomBytes(48).toString("base64url"),
    MINIO_ACCESS_KEY: randomBytes(16).toString("hex"),
    MINIO_SECRET_KEY: randomBytes(32).toString("hex"),
    ONLYOFFICE_JWT_SECRET: randomBytes(32).toString("hex"),
    DEMO_ADMIN_PASSWORD: randomBytes(18).toString("base64url"),
    DEMO_TEACHER_PASSWORD: randomBytes(18).toString("base64url"),
    DEMO_STUDENT_PASSWORD: randomBytes(18).toString("base64url"),
    DEMO_STUDENT2_PASSWORD: randomBytes(18).toString("base64url"),
    WEB_ORIGIN: "http://localhost:3000,http://localhost:5173"
  }
  const result = template.replace(/^([A-Z][A-Z0-9_]*)=.*$/gm, (line, key) =>
    Object.hasOwn(values, key) ? `${key}=${values[key]}` : line
  )
  for (const key of Object.keys(values)) {
    if (!new RegExp(`^${key}=`, "m").test(result)) throw new Error(`环境模板缺少配置项 ${key}`)
  }
  if (/^[A-Z][A-Z0-9_]*=.*replace[-_]/m.test(result)) throw new Error("环境模板存在未生成的占位配置")
  return result
}

export async function setupLocalEnvironment(directory = repositoryDirectory) {
  const environmentPath = resolve(directory, ".env")
  try {
    await stat(environmentPath)
    return { created: false, path: environmentPath }
  } catch (error) {
    if (error.code !== "ENOENT") throw error
  }
  const template = await readFile(resolve(directory, ".env.example"), "utf8")
  const content = createLocalEnvironment(template)
  try {
    // Exclusive creation also prevents a concurrent invocation from replacing
    // values that were just generated by another process.
    await writeFile(environmentPath, content, { encoding: "utf8", flag: "wx", mode: 0o600 })
    return { created: true, path: environmentPath }
  } catch (error) {
    if (error.code === "EEXIST") return { created: false, path: environmentPath }
    throw error
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const result = await setupLocalEnvironment()
    console.log(result.created
      ? "已创建本地 .env。登录密码保存在 DEMO_*_PASSWORD 配置项中；终端不显示密码。"
      : "已保留现有 .env。请确认数据库与演示账号配置完整后启动。")
  } catch (error) {
    console.error(`本地环境初始化失败：${error.message}`)
    process.exitCode = 1
  }
}
